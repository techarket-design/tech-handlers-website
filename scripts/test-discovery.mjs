import assert from 'node:assert/strict';
import { discoverySitemap, blogFeed, publicEntry } from '../server/discovery.mjs';
import { changedUrls, submitUrls } from '../server/indexnow.mjs';
const base = 'https://www.techhandlers.in';
const index = await discoverySitemap(undefined, 1, undefined, async table => table === 'blog_posts' ? 1001 : 0);
assert.match(index, /sitemap-blog-3.xml/);
assert.doesNotMatch(index, /sitemap-blog-4.xml/);
assert.match(index, /sitemap-pages.xml/);
let request;
const shard = await discoverySitemap('blog', 3, async (table, params) => {
  request = params;
  return [ { slug: 'growth', updated_at: '2026-10-02', featured_image_url: 'https://images.example/a?x=1&y=2' }, { slug: 'draft', noindex: true }, { slug: 'duplicate', canonical_url: base + '/blog/other' }, { slug: '../bad' } ];
});
assert.equal(request.offset, '1000');
assert.match(shard, /2026-10-02T00:00:00.000Z/);
assert.match(shard, /image:loc/);
assert.match(shard, /&amp;y=2/);
assert.doesNotMatch(shard, /draft|duplicate|bad/);
assert.equal(await discoverySitemap('invalid'), null);
assert.equal(await discoverySitemap('blog', 0), null);
assert.equal(publicEntry({ slug: 'hidden', noindex: true }, 'blog'), null);
const event = { schema: 'public', table: 'blog_posts', type: 'UPDATE', record: { slug: 'new', is_published: true }, old_record: { slug: 'old', is_published: true } };
assert.deepEqual(changedUrls(event), [base + '/blog/new', base + '/blog/old']);
assert.deepEqual(changedUrls({ ...event, record: { slug: 'new', is_published: false } }), [base + '/blog/old']);
assert.deepEqual(changedUrls({ ...event, table: 'leads' }), []);
assert.deepEqual(changedUrls({ ...event, type: 'INSERT', record: { slug: 'draft', is_published: false }, old_record: null }), []);
const feed = await blogFeed(async () => [{ title: 'SEO & growth', slug: 'growth', excerpt: '<Useful>', published_at: '2026-10-02' }, { title: 'Hidden', slug: 'hidden', noindex: true }]);
assert.match(feed, /SEO &amp; growth/);
assert.doesNotMatch(feed, /Hidden/);
process.env.INDEXNOW_KEY = 'test-key-12345678';
let payload;
assert.equal(await submitUrls([base + '/blog/new'], async (url, options) => { payload = JSON.parse(options.body); return { status: 202 }; }), 202);
assert.equal(payload.keyLocation, base + '/indexnow-key.txt');
await assert.rejects(submitUrls([base + '/blog/new'], async () => ({ status: 429 })));
console.log('Discovery: pagination, canonical/noindex exclusion, image XML, RSS, publish/unpublish/slug changes and IndexNow acceptance verified');
